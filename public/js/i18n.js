const DICT = { es, en, pt };

/** Translate a key. `{name}` placeholders are filled from `vars` (callers escape HTML themselves). */
export function translate(lang, key, vars) {
  let s = DICT[lang]?.[key] ?? DICT.es[key] ?? DICT.en[key];
  if (s === undefined) return key;
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
export const hasKey = (key) => Object.hasOwn(DICT.en, key);

const isEmpty = (v) => v == null || (Array.isArray(v) ? v.length === 0 : typeof v === 'object' ? Object.keys(v).length === 0 : String(v).trim() === '');

/** Product text in the requested language, falling back to Spanish field by field. */
export function localizeProduct(p, lang) {
  if (!p || lang === DEFAULT_LANG || !p.tr?.[lang]) return p;
  const out = { ...p };
  for (const f of TEXT_FIELDS) if (!isEmpty(p.tr[lang][f])) out[f] = p.tr[lang][f];
  return out;
}

export function formatMoney(lang, n) {
  return new Intl.NumberFormat(LANGS[lang]?.locale || 'es-US', { style: 'currency', currency: 'USD' }).format(n);
}

export function countryName(lang, code) {
  try { return new Intl.DisplayNames([LANGS[lang]?.locale || 'es-US'], { type: 'region' }).of(code); } catch { return code; }
}
